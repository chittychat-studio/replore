"""SPEC RS84: copy the ranking eval cases into web/evals.json for the public "How ranking is tested" page.

Run after editing evals/fit_cases.json or evals/hybrid_cases.json:  python ops/build_evals_page.py
(tests/test_site.py fails while web/evals.json is stale.) Standard library only. Only our own case data is copied:
names, goals, the inputs each case ranks and the expected answer. Em dashes become colons or commas (RS66: no em dash
in site copy); the files under evals/ keep their wording.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "evals.json"


def copy_text(s):
    """Site copy: no em dashes (RS66), single spaces."""
    s = re.sub(r"\s*—\s*", ": ", str(s or ""), count=1)
    s = re.sub(r"\s*—\s*", ", ", s)
    return re.sub(r"\s+", " ", s).strip()


def build():
    fit = json.loads((ROOT / "evals" / "fit_cases.json").read_text(encoding="utf-8"))
    hyb = json.loads((ROOT / "evals" / "hybrid_cases.json").read_text(encoding="utf-8"))
    fit_cases = [{
        "name": copy_text(c["name"]),
        "goal": copy_text(c["goal"]),
        "prefer_starters": bool(c.get("prefer_starters", False)),
        "candidates": [{"name": x["name"], "position": x.get("rel", 0), "stars": x["stars"], "licence": x.get("spdx") or "none",
                        "starter": bool(x.get("starter", False))} for x in c["candidates"]],
        "expect_top": c["expect_top"],
    } for c in fit["cases"]]
    hyb_cases = []
    for c in hyb["cases"]:
        exp = c["expect"]
        hyb_cases.append({
            "name": copy_text(c["name"]),
            "goal": copy_text(c["goal"]),
            "description": "(a 2,000-character description)" if c["description"] == "LONG" else copy_text(c["description"]),
            "rows": [r["name"] for r in c["rows"]],
            "meaning_scores": c.get("sims"),
            "expect": ("first: " + exp["first"]) if "first" in exp else ("order unchanged" if "unchanged" in exp else "exact order"),
            "expect_order": c.get("parity") or exp.get("order") or [r["name"] for r in c["rows"]],
        })
    return {
        "_about": "Generated by ops/build_evals_page.py from evals/fit_cases.json and evals/hybrid_cases.json (SPEC RS84). Do not edit by hand.",
        "fit": {"threshold": fit.get("threshold", 1.0), "cases": fit_cases},
        "hybrid": {"threshold": hyb.get("threshold", 1.0), "cases": hyb_cases},
    }


def render(data):
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def main():
    OUT.write_text(render(build()), encoding="utf-8", newline="\n")
    d = build()
    print("wrote web/evals.json: %d fit cases, %d hybrid cases" % (len(d["fit"]["cases"]), len(d["hybrid"]["cases"])))


if __name__ == "__main__":
    main()
